async function harness() {
  const fixture = await startFixture()
  const local = await fs.mkdtemp(path.join(os.tmpdir(), 'ssh-heaven-transfer-tests-'))
  const store = new AppStore(path.join(local, 'settings.json'))
  await store.load()
  const notifications = new EventEmitter()
  let terminal = ''
  const ownerId = 201
  const sessionId = 'transfer-session'
  const service = new SshService(store, {
    hostKey(owner, challenge) { queueMicrotask(() => service.resolveHostKey(owner, challenge.requestId, true)) },
    status() {},
    data(_owner, event) { terminal += Buffer.from(event.data).toString('utf8'); notifications.emit('data') }
  })
  await service.connect({
    sessionId, password: fixture.password,
    profile: { id: 'fixture-profile', name: 'Transfer fixture', host: fixture.host, port: fixture.port, username: fixture.username, authType: 'password' }
  }, ownerId)
  const events: TransferJob[] = []
  let hook: (event: TransferJob) => void = () => {}
  const manager = new TransferManager((owner, id) => service.getSftp(owner, id), (owner, event) => {
    assert.equal(owner, ownerId)
    events.push({ ...event })
    hook(event)
  })
  return {
    fixture, local, service, manager, events, ownerId, sessionId,
    setHook(callback: (event: TransferJob) => void) { hook = callback },
    async assertShellUsable() {
      const marker = `transfer-shell-${Date.now()}`
      service.write(ownerId, sessionId, `echo ${marker}\r`)
      await new Promise<void>((resolve, reject) => {
        const cleanup = () => { clearTimeout(timer); notifications.off('data', changed) }
        const changed = () => { if (terminal.includes(`\r\n${marker}\r\n`)) { cleanup(); resolve() } }
        const timer = setTimeout(() => { cleanup(); reject(new Error('Shell stopped responding after transfer')) }, 5000)
        notifications.on('data', changed)
        changed()
      })
    },
    async close() {
      await manager.dispose()
      service.dispose()
      await fixture.close()
      // local is generated by mkdtemp and never accepts remote path input.
      await fs.rm(local, { recursive: true, force: true })
    }
  }
}

test('recursive folders round-trip binary files and empty directories with aggregate progress', { timeout: 20_000 }, async () => {
  const h = await harness()
  try {
    const source = path.join(h.local, 'project')
    await fs.mkdir(path.join(source, 'nested', 'empty'), { recursive: true })
    const bytes = randomBytes(234_567)
    await fs.writeFile(path.join(source, 'nested', 'data.bin'), bytes)
    await fs.writeFile(path.join(source, 'readme.txt'), 'Folder transfer fixture')
    const uploaded = await h.manager.upload(h.ownerId, h.sessionId, [source], '/', async () => true)
    assert.deepEqual(uploaded.files, ['/project'])
    assert.deepEqual(await fs.readFile(path.join(h.fixture.root, 'project', 'nested', 'data.bin')), bytes)
    assert.deepEqual(await fs.readdir(path.join(h.fixture.root, 'project', 'nested', 'empty')), [])
    const result = [...h.events].reverse().find((event) => event.status === 'completed')!
    assert.equal(result.transferred, bytes.length + Buffer.byteLength('Folder transfer fixture'))
    assert.equal(result.transferred, result.total)
    const downloads = path.join(h.local, 'downloads')
    await fs.mkdir(downloads)
    await h.manager.download(h.ownerId, h.sessionId, ['/project'], downloads, async () => true)
    assert.deepEqual(await fs.readFile(path.join(downloads, 'project', 'nested', 'data.bin')), bytes)
    assert.deepEqual(await fs.readdir(path.join(downloads, 'project', 'nested', 'empty')), [])
    await h.assertShellUsable()
  } finally { await h.close() }
})

test('canceled folder jobs clean temporary files and can retry without giving another window access', { timeout: 20_000 }, async () => {
  const h = await harness()
  try {
    const source = path.join(h.local, 'retry-folder')
    await fs.mkdir(source)
    const bytes = randomBytes(2 * 1024 * 1024)
    await fs.writeFile(path.join(source, 'data.bin'), bytes)
    let canceledId = ''
    h.setHook((event) => { if (!canceledId && event.name === 'retry-folder' && event.transferred > 64 * 1024 && event.status === 'running') { canceledId = event.id; h.manager.cancel(h.ownerId, event.id) } })
    assert.equal((await h.manager.upload(h.ownerId, h.sessionId, [source], '/', async () => true)).canceled, true)
    assert.ok(canceledId)
    assert.equal((await fs.readdir(path.join(h.fixture.root, 'retry-folder'))).some((name) => name.endsWith('.part')), false)
    await assert.rejects(h.manager.retry(999, canceledId, async () => true), /this window/)
    h.setHook(() => {})
    assert.deepEqual((await h.manager.retry(h.ownerId, canceledId, async () => true)).files, ['/retry-folder'])
    assert.deepEqual(await fs.readFile(path.join(h.fixture.root, 'retry-folder', 'data.bin')), bytes)
    await h.assertShellUsable()
  } finally { await h.close() }
})

test('folder preflight rejects symbolic links and unsafe remote names before creating destinations', { timeout: 20_000 }, async () => {
  const h = await harness()
  try {
    const source = path.join(h.local, 'links')
    const outside = path.join(h.local, 'outside')
    await fs.mkdir(source); await fs.mkdir(outside)
    await fs.writeFile(path.join(outside, 'private.txt'), 'Must not be followed')
    await fs.symlink(outside, path.join(source, 'outside-link'), process.platform === 'win32' ? 'junction' : 'dir')
    await assert.rejects(h.manager.upload(h.ownerId, h.sessionId, [source], '/', async () => true), /symbolic links/)
    await assert.rejects(fs.stat(path.join(h.fixture.root, 'links')), { code: 'ENOENT' })
    const mock = {
      lstat(_filename: string, callback: (error: null, value: object) => void) { callback(null, { isDirectory: () => true, isFile: () => false, isSymbolicLink: () => false, size: 0 }) },
      readdir(_filename: string, callback: (error: null, value: object[]) => void) { callback(null, [{ filename: '../escape' }]) }
    } as unknown as SFTPWrapper
    await assert.rejects(scanRemoteTree(mock, '/folder', new AbortController().signal), /path separators/)
  } finally { await h.close() }
})

test('transfer queues stream binary batches in order and report accurate byte totals', { timeout: 20_000 }, async () => {
  const h = await harness()
  try {
    const first = randomBytes(280_123)
    const second = randomBytes(180_045)
    const sources = [path.join(h.local, 'first.bin'), path.join(h.local, 'second.bin')]
    await Promise.all([fs.writeFile(sources[0], first), fs.writeFile(sources[1], second)])
    const uploaded = await h.manager.upload(h.ownerId, h.sessionId, sources, '/', async () => true)
    assert.deepEqual(uploaded, { canceled: false, files: ['/first.bin', '/second.bin'] })
    assert.deepEqual(await fs.readFile(path.join(h.fixture.root, 'first.bin')), first)
    assert.deepEqual(await fs.readFile(path.join(h.fixture.root, 'second.bin')), second)
    const completed = h.events.filter((event) => event.status === 'completed')
    assert.equal(completed.length, 2)
    assert.deepEqual(completed.map((event) => [event.transferred, event.total]), [[first.length, first.length], [second.length, second.length]])
    const firstCompletedIndex = h.events.findIndex((event) => event.name === 'first.bin' && event.status === 'completed')
    const secondRunningIndex = h.events.findIndex((event) => event.name === 'second.bin' && event.status === 'running')
    assert.ok(firstCompletedIndex < secondRunningIndex, 'One session must stream one queued file at a time')
    assert.ok(h.events.some((event) => event.status === 'running' && event.transferred > 0 && event.transferred < event.total))
    assert.ok(completed.every((event) => event.finishedAt && event.finishedAt >= event.startedAt))
    const downloads = path.join(h.local, 'downloads')
    await fs.mkdir(downloads)
    const downloaded = await h.manager.download(h.ownerId, h.sessionId, ['/first.bin', '/second.bin'], downloads, async () => true)
    assert.deepEqual(downloaded.files, [path.join(downloads, 'first.bin'), path.join(downloads, 'second.bin')])
    assert.deepEqual(await fs.readFile(downloaded.files[0]), first)
    assert.deepEqual(await fs.readFile(downloaded.files[1]), second)
    assert.equal((await fs.readdir(h.fixture.root)).some((name) => name.endsWith('.part')), false)
    assert.equal((await fs.readdir(downloads)).some((name) => name.endsWith('.part')), false)
    await h.assertShellUsable()
  } finally { await h.close() }
})

test('canceling running and queued transfers preserves originals, cleans temporary files, and keeps SSH usable', { timeout: 20_000 }, async () => {
  const h = await harness()
  try {
    const original = Buffer.from('Keep the original remote file intact.')
    const source = path.join(h.local, 'preserved.bin')
    const queued = path.join(h.local, 'queued.bin')
    await fs.writeFile(path.join(h.fixture.root, 'preserved.bin'), original)
    await fs.writeFile(source, randomBytes(4 * 1024 * 1024))
    await fs.writeFile(queued, randomBytes(1024))
    let acknowledgedAtCancel = 0
    h.setHook((event) => {
      if (event.name === 'queued.bin' && event.status === 'queued') {
        assert.throws(() => h.manager.cancel(999, event.id), /another window/)
        h.manager.cancel(h.ownerId, event.id)
      }
      if (event.name === 'preserved.bin' && event.status === 'running' && event.transferred > 64 * 1024) {
        const temporary = readdirSync(h.fixture.root).find((name) => name.endsWith('.part'))
        if (temporary) {
          const acknowledged = statSync(path.join(h.fixture.root, temporary)).size
          if (acknowledged > 64 * 1024) {
            acknowledgedAtCancel = acknowledged
            h.manager.cancel(h.ownerId, event.id)
          }
        }
      }
    })
    const result = await h.manager.upload(h.ownerId, h.sessionId, [source, queued], '/', async () => true)
    assert.deepEqual(result, { canceled: true, files: [] })
    assert.ok(acknowledgedAtCancel > 64 * 1024, 'Cancel only after the server has actually written more than 64 KiB')
    assert.deepEqual(await fs.readFile(path.join(h.fixture.root, 'preserved.bin')), original)
    assert.equal((await fs.readdir(h.fixture.root)).some((name) => name.endsWith('.part') || name === 'queued.bin'), false)
    assert.equal(h.events.filter((event) => event.status === 'canceled').length, 2)
    await h.assertShellUsable()

    const downloads = path.join(h.local, 'downloads')
    await fs.mkdir(downloads)
    const localOriginal = Buffer.from('Keep the original local file intact.')
    await fs.writeFile(path.join(downloads, 'preserved.bin'), localOriginal)
    await fs.writeFile(path.join(h.fixture.root, 'preserved.bin'), randomBytes(4 * 1024 * 1024))
    h.setHook((event) => {
      if (event.direction === 'download' && event.status === 'running' && event.transferred > 0) h.manager.cancel(h.ownerId, event.id)
    })
    assert.deepEqual(await h.manager.download(h.ownerId, h.sessionId, ['/preserved.bin'], downloads, async () => true), { canceled: true, files: [] })
    assert.deepEqual(await fs.readFile(path.join(downloads, 'preserved.bin')), localOriginal)
    assert.deepEqual(await fs.readdir(downloads), ['preserved.bin'])
    await h.assertShellUsable()
  } finally { await h.close() }
})

test('cancellation waits for delayed remote OPEN/CLOSE callbacks before settling and removing temporary siblings', { timeout: 20_000 }, async () => {
  const h = await harness()
  try {
    const source = path.join(h.local, 'delayed.bin')
    await fs.writeFile(source, randomBytes(512 * 1024))
    const sftp = await h.service.getSftp(h.ownerId, h.sessionId)
    let pendingClose = 0
    let cleanupRacedClose = false
    let delayed: SFTPWrapper
    delayed = new Proxy(sftp, {
      get(target, property) {
        if (property === 'open') return (...args: Parameters<SFTPWrapper['open']>) => { setTimeout(() => target.open(...args), 80) }
        if (property === 'close') return (handle: Buffer, callback: (error?: Error | null) => void) => {
          pendingClose++
          setTimeout(() => target.close(handle, (error) => { pendingClose--; callback(error) }), 80)
        }
        if (property === 'unlink') return (filename: string, callback: (error?: Error | null) => void) => {
          if (pendingClose) cleanupRacedClose = true
          target.unlink(filename, callback)
        }
        // Stream constructors must retain the proxy, so their OPEN and CLOSE
        // really traverse the delayed SSH operations above.
        if (property === 'createWriteStream') return (...args: Parameters<SFTPWrapper['createWriteStream']>) => target.createWriteStream.call(delayed, ...args)
        const value = Reflect.get(target, property, target)
        return typeof value === 'function' ? value.bind(target) : value
      }
    }) as SFTPWrapper
    let manager: TransferManager
    const events: TransferJob[] = []
    manager = new TransferManager(async () => delayed, (_owner, event) => {
      events.push(event)
      if (event.status === 'running' && event.transferred > 0) manager.cancel(h.ownerId, event.id)
    })
    const result = await manager.upload(h.ownerId, h.sessionId, [source], '/', async () => true)
    assert.equal(result.canceled, true)
    assert.equal(pendingClose, 0, 'Batch completion must wait for acknowledged remote close')
    assert.equal(cleanupRacedClose, false, 'Temporary cleanup must run after remote close')
    assert.equal(events.at(-1)?.status, 'canceled')
    assert.equal((await fs.readdir(h.fixture.root)).some((name) => name.endsWith('.part') || name === 'delayed.bin'), false)
    // A late OPEN used to recreate the temporary file after queue completion.
    await new Promise((resolve) => setTimeout(resolve, 220))
    assert.equal((await fs.readdir(h.fixture.root)).some((name) => name.endsWith('.part')), false)
    await manager.dispose()
    await h.assertShellUsable()
  } finally { await h.close() }
})

test('a server without safe overwrite support leaves the original intact and cleans the uploaded sibling', { timeout: 20_000 }, async () => {
  const h = await harness()
  try {
    const source = path.join(h.local, 'welcome.txt')
    await fs.writeFile(source, 'Replacement that the server must reject.')
    const original = await fs.readFile(path.join(h.fixture.root, 'welcome.txt'))
    const sftp = await h.service.getSftp(h.ownerId, h.sessionId)
    // Actual SSH/SFTP streams are used. Only final rename capability is changed
    // to simulate a server that cannot replace an existing destination.
    const limited = new Proxy(sftp, {
      get(target, property) {
        if (property === 'ext_openssh_rename') return () => { throw new Error('Server does not support this extended request') }
        if (property === 'rename') return (_source: string, _destination: string, callback: (error: Error) => void) => callback(new Error('Destination already exists'))
        const value = Reflect.get(target, property, target)
        return typeof value === 'function' ? value.bind(target) : value
      }
    }) as SFTPWrapper
    const events: TransferJob[] = []
    const manager = new TransferManager(async () => limited, (_owner, event) => events.push(event))
    await assert.rejects(manager.upload(h.ownerId, h.sessionId, [source], '/', async () => true), /original file was preserved/)
    assert.deepEqual(await fs.readFile(path.join(h.fixture.root, 'welcome.txt')), original)
    assert.equal((await fs.readdir(h.fixture.root)).some((name) => name.endsWith('.part')), false)
    assert.equal(events.at(-1)?.status, 'failed')
    await manager.dispose()
    await h.assertShellUsable()
  } finally { await h.close() }
})

test('empty files complete and declined replacements keep both local and remote originals', { timeout: 20_000 }, async () => {
  const h = await harness()
  try {
    const emptySource = path.join(h.local, 'empty.txt')
    await fs.writeFile(emptySource, '')
    await h.manager.upload(h.ownerId, h.sessionId, [emptySource], '/', async () => true)
    const downloads = path.join(h.local, 'downloads')
    await fs.mkdir(downloads)
    await h.manager.download(h.ownerId, h.sessionId, ['/empty.txt'], downloads, async () => true)
    assert.equal((await fs.stat(path.join(h.fixture.root, 'empty.txt'))).size, 0)
    assert.equal((await fs.stat(path.join(downloads, 'empty.txt'))).size, 0)
    const replacement = path.join(h.local, 'welcome.txt')
    await fs.writeFile(replacement, 'Replacement contents')
    const remoteOriginal = await fs.readFile(path.join(h.fixture.root, 'welcome.txt'))
    assert.equal((await h.manager.upload(h.ownerId, h.sessionId, [replacement], '/', async () => false)).canceled, true)
    assert.deepEqual(await fs.readFile(path.join(h.fixture.root, 'welcome.txt')), remoteOriginal)
    const localOriginal = Buffer.from('Keep this local copy')
    await fs.writeFile(path.join(downloads, 'welcome.txt'), localOriginal)
    assert.equal((await h.manager.download(h.ownerId, h.sessionId, ['/welcome.txt'], downloads, async () => false)).canceled, true)
    assert.deepEqual(await fs.readFile(path.join(downloads, 'welcome.txt')), localOriginal)
    // The fixture supports standard rename but not OpenSSH's extension. A safe
    // fallback that succeeds must still commit the complete replacement.
    await h.manager.upload(h.ownerId, h.sessionId, [replacement], '/', async () => true)
    assert.equal(await fs.readFile(path.join(h.fixture.root, 'welcome.txt'), 'utf8'), 'Replacement contents')
    await h.assertShellUsable()
  } finally { await h.close() }
})
