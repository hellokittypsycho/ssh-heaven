    const completed = h.events.filter((event) => event.status === 'completed')
    assert.equal(completed.length, 2)
    assert.deepEqual(completed.map((event) => [event.transferred, event.total]), [[first.length, first.length], [second.length, second.length]])
    const firstCompletedIndex = h.events.findIndex((event) => event.name === 'first.bin' && event.status === 'completed')
    const secondRunningIndex = h.events.findIndex((event) => event.name === 'second.bin' && event.status === 'running')
    assert.ok(firstCompletedIndex < secondRunningIndex, 'One session must stream one queued file at a time')
    assert.ok(h.events.some((event) => event.status === 'running' && event.transferred > 0 && event.transferred < event.total))
    assert.ok(completed.every((event) => event.finishedAt && event.finishedAt >= event.startedAt))
    const downloads = path.join(h.local, 'downloads')
